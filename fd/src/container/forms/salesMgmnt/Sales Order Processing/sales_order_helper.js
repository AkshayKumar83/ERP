export const createSearchPayload = (masterData) => {
  const masterKeys = {
    order_no: "order_no",
    order_dt: "order_dt",
    c_code: "c_code",
  };

  return Object.keys(masterKeys).reduce((payload, key) => {
    if (masterData[key]) {
      payload[masterKeys[key]] = masterData[key];
    }
    return payload;
  }, {});
};

