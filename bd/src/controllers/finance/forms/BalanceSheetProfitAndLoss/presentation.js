        trans_year: data.trans_year || user?.global_fin_year || null,
        bs_pl_flag: data.bs_pl_flag || 'B',
        ass_lib_inc_exp_app_sch_flag: data.ass_lib_inc_exp_app_sch_flag || 'A',
